#!/usr/bin/env python3
"""Build the kubectl command index from the official generated kubectl reference.

Source: kubernetes/website content/en/docs/reference/kubectl/generated/ for the version in
skills/cka-rules/references/kubectl/VERSION. The docs branch for the latest release is `main`,
older ones are `release-1.xx`. The resolved commit SHA is written into every file.
Pure code conversion (no summarizing): command, synopsis, usage, own flags, subcommands.
Global flags are the same on every page, so they live only in kubectl.md.

Usage: build_kubectl_index.py [--ref <branch|sha>] | --selftest
"""
import html
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "skills" / "cka-rules" / "references" / "kubectl"
REPO = "kubernetes/website"
DOCS = "content/en/docs/reference/kubectl/generated/"
LICENSE = "Kubernetes Documentation, CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/)"

SECTION = re.compile(r"^## \{\{% heading \"(\w+)\" %\}\}\s*$", re.M)
FLAG_ROW = re.compile(
    r'<td colspan="2">(.*?)</td>\s*</tr>\s*<tr>\s*<td></td><td[^>]*>(.*?)</td>', re.S)
FLAG_HEAD = re.compile(r"^(?:-(?P<short>\w), )?--(?P<name>[\w-]+)(?: (?P<type>.+))?$")
SEEALSO = re.compile(r"^\* \[(?P<cmd>[^\]]+)\]\((?P<href>[^)]+)\)\s*- (?P<desc>.*)$", re.M)


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "ai-k8s-make-believe-index"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")


def one_line(text):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", text))).strip()


def parse_flags(body):
    flags = []
    for head, desc in FLAG_ROW.findall(body or ""):
        head, _, default = html.unescape(head).replace("\xa0", " ").partition("Default:")
        m = FLAG_HEAD.match(head.strip())
        if not m:
            raise ValueError(f"unexpected flag header: {head!r}")
        flags.append({"name": m["name"], "short": m["short"] or "", "type": m["type"] or "bool",
                      "default": default.strip(), "desc": one_line(desc)})
    return flags


def parse_page(text):
    title = re.search(r"^title: (.+)$", text, re.M).group(1).strip()
    parts = SECTION.split(text)
    sections = dict(zip(parts[1::2], parts[2::2]))
    synopsis = sections.get("synopsis", "")
    usage = re.search(r"```\n(.*?)\n```", synopsis, re.S)
    summary = one_line(re.sub(r"```.*?```", "", synopsis, flags=re.S))
    subs = [m["cmd"] for m in SEEALSO.finditer(sections.get("seealso", ""))
            if m["cmd"].startswith(title + " ")]
    return {"command": title, "summary": summary, "usage": usage.group(1).strip() if usage else "",
            "flags": parse_flags(sections.get("options")),
            "parent_flags": parse_flags(sections.get("parentoptions")), "subcommands": subs}


def cell(s):
    return s.replace("|", "\\|")


def render(page, source, global_names):
    lines = [f"<!-- source: {source} | {LICENSE} | generated by scripts/build_kubectl_index.py -->",
             f"# {page['command']}", "", page["summary"], ""]
    if page["usage"]:
        lines += ["```", page["usage"], "```", ""]
    if page["subcommands"]:
        lines += ["하위 명령: " + ", ".join(s.split()[-1] for s in page["subcommands"]), ""]
    own = page["flags"]
    extra = [f for f in page["parent_flags"] if f["name"] not in global_names]
    if own or extra:
        lines += ["| flag | short | type | default | description |", "|---|---|---|---|---|"]
        lines += [f"| --{f['name']} | {f['short'] and '-' + f['short']} | {f['type']} | "
                  f"{cell(f['default'])} | {cell(f['desc'])} |" for f in own + extra]
        lines.append("")
    if page["command"] != "kubectl":
        lines.append("전역 플래그(--namespace, --context 등)는 kubectl.md 참고.")
    return "\n".join(lines).rstrip() + "\n"


def out_name(path):
    rel = path[len(DOCS):]
    if rel == "_index.md":
        return None
    if rel.endswith("/_index.md"):
        return rel[: -len("/_index.md")].split("/")[-1] + ".md"
    return rel.split("/")[-1]


def resolve_ref(version):
    hugo = get(f"https://raw.githubusercontent.com/{REPO}/main/hugo.toml")
    latest = re.search(r'^latest = "(v[\d.]+)"', hugo, re.M).group(1)
    return "main" if latest == version else "release-" + version.lstrip("v")


def build(ref):
    version = (OUT / "VERSION").read_text().strip()
    branch = ref or resolve_ref(version)
    sha = json.loads(get(f"https://api.github.com/repos/{REPO}/commits/{branch}"))["sha"]
    tree = json.loads(get(f"https://api.github.com/repos/{REPO}/git/trees/{sha}?recursive=1"))
    if tree.get("truncated"):
        sys.exit("git tree truncated: 일부 파일을 놓칠 수 있어 중단합니다")
    paths = sorted(t["path"] for t in tree["tree"]
                   if t["type"] == "blob" and t["path"].startswith(DOCS) and t["path"].endswith(".md"))
    pages = {}
    for p in paths:
        name = out_name(p)
        if name:
            try:
                pages[name] = (parse_page(get(f"https://raw.githubusercontent.com/{REPO}/{sha}/{p}")), p)
            except ValueError as e:
                sys.exit(f"{p}: {e}")
    root = pages["kubectl.md"][0]
    global_names = {f["name"] for f in root["flags"]}
    for old in OUT.glob("kubectl*.md"):
        old.unlink()
    for name, (page, p) in pages.items():
        source = f"https://github.com/{REPO}/blob/{sha}/{p} (branch {branch}, {version})"
        (OUT / name).write_text(render(page, source, global_names), encoding="utf-8")
    print(f"{len(pages)} files from {REPO}@{sha[:12]} ({branch}, {version}) -> {OUT.relative_to(ROOT)}")


