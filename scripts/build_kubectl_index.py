def _selftest():
    page = parse_page(SAMPLE)
    assert page["command"] == "kubectl create deployment"
    assert page["summary"] == "Create a deployment with the specified name."
    assert page["usage"].startswith("kubectl create deployment NAME --image=image")
    f = {x["name"]: x for x in page["flags"]}
    assert f["dry-run"] == {"name": "dry-run", "short": "", "type": 'string[="unchanged"]',
                            "default": '"none"', "desc": 'Must be "none", "server", or "client".'}
    assert f["replicas"]["short"] == "r" and f["replicas"]["type"] == "int32" and f["replicas"]["default"] == "1"
    assert f["save-config"]["type"] == "bool" and f["save-config"]["desc"] == "If true, save config."
    assert f["aggregation-rule"]["type"] == "<comma-separated 'key=value' pairs>"
    assert page["subcommands"] == ["kubectl create deployment sub"]  # parent link excluded
    out = render(page, "SRC", {"namespace"})
    assert "| --namespace" not in out  # global flags only in kubectl.md
    assert "| --replicas | -r | int32 | 1 | Number of replicas \\| to create. |" in out
    assert "하위 명령: sub" in out and "CC BY 4.0" in out
    assert out_name(DOCS + "kubectl_create/_index.md") == "kubectl_create.md"
    assert out_name(DOCS + "kubectl_create/kubectl_create_deployment.md") == "kubectl_create_deployment.md"
    assert out_name(DOCS + "kubectl.md") == "kubectl.md" and out_name(DOCS + "_index.md") is None
    print("selftest ok")


if __name__ == "__main__":
    args = sys.argv[1:]
    if args == ["--selftest"]:
        _selftest()
    elif not args:
        build(None)
    elif len(args) == 2 and args[0] == "--ref":
        build(args[1])
    else:
        sys.exit(__doc__)
