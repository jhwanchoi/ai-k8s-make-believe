#!/usr/bin/env python3
"""skills/cka-rules/references/kubectl/*.md 색인을 시뮬레이터 화면용 simulator/static/kubectl-flags.js 로 바꾼다.

브라우저는 색인 md 를 읽을 수 없어서, 명령마다 하위 명령과 플래그(이름, 단축, 타입)만 뽑아 JS 한 파일로 둔다.
색인을 다시 만들면 이 스크립트도 다시 실행한다. 네트워크를 쓰지 않는다.
Usage: build_kubectl_flags_js.py | --selftest
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "skills" / "cka-rules" / "references" / "kubectl"
OUT = ROOT / "simulator" / "static" / "kubectl-flags.js"
ROW = re.compile(r"^\| --([\w-]+) \| (?:-(\w))? *\| ([^|]+?) \|", re.M)
SUBS = re.compile(r"^하위 명령: (.+)$", re.M)


def parse(text):
    flags, short = {}, {}
    for name, sh, typ in ROW.findall(text):
        # string[="unchanged"]: 값 없이도 쓰는 플래그라 다음 단어를 값으로 먹지 않는다. 판정에는 bool 과 같다.
        typ = "bool" if "[=" in typ else typ
        flags[name] = typ
        if sh:
            short[sh] = typ
    m = SUBS.search(text)
    subs = [s.strip() for s in m.group(1).split(",")] if m else []
    return {"flags": flags, "short": short, "subs": subs}


def build():
    commands = {}
    for md in sorted(INDEX.glob("kubectl*.md")):
        path = md.stem.split("_")[1:]  # kubectl_create_deployment -> ["create", "deployment"]
        commands[" ".join(path)] = parse(md.read_text(encoding="utf-8"))
    version = (INDEX / "VERSION").read_text(encoding="utf-8").strip()
    data = {"version": version, "commands": commands}
    OUT.write_text(
        "// generated by scripts/build_kubectl_flags_js.py from skills/cka-rules/references/kubectl "
        "(Kubernetes Documentation, CC BY 4.0). Do not edit.\n"
        f"window.KUBECTL_INDEX = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print(f"{OUT.relative_to(ROOT)}: {len(commands)} commands, {OUT.stat().st_size} bytes")


def _selftest():
    sample = (
        "하위 명령: get, create\n\n| flag | short | type | default | description |\n|---|---|---|---|---|\n"
        "| --all-namespaces | -A | bool |  | x |\n| --chunk-size |  | int | 500 | y |\n"
        '| --dry-run |  | string[="unchanged"] | "none" | z |\n'
    )
    p = parse(sample)
    assert p["flags"] == {"all-namespaces": "bool", "chunk-size": "int", "dry-run": "bool"}, p
    assert p["short"] == {"A": "bool"}, p
    assert p["subs"] == ["get", "create"], p
    assert parse("no table") == {"flags": {}, "short": {}, "subs": []}
    print("selftest ok")


if __name__ == "__main__":
    _selftest() if sys.argv[1:] == ["--selftest"] else build()
